"""Async QR-code issuing, companion activation, and secure scanning.

Responsibilities
----------------
- ``issue_qr_codes_for_ticket``: create the codes a CONFIRMED ticket is
  entitled to (one GRADUATE code plus its COMPANION codes). Idempotent and
  protected by a row-level lock (FR-24 / UC-10).
- ``activate_companion_codes``: flip the ticket's COMPANION codes on right
  after the graduate's code is scanned (UC-12).
- ``scan_qr_code``: the core of FR-25 / UC-11. Uses ``SELECT ... FOR UPDATE``
  so two scanners can never consume the same code concurrently, and returns a
  :class:`ScanResult` describing exactly what happened.

Constraints
-----------
- No database connections are created here; the caller passes a live session
  and owns the transaction (this module only ``flush``-es).
- Compare enums against :class:`QrCodeTypeEnum` / ``TicketStatusEnum`` members,
  never against their ``.value`` strings.
- The QR value is a UUID generated by the database default (``gen_random_uuid``);
  it is never generated in Python so the value can never be predicted.
"""

import uuid
from dataclasses import dataclass
from datetime import UTC, datetime
from enum import Enum

from sqlalchemy import select, update
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.messages import (
    SCAN_ALREADY_USED,
    SCAN_NOT_ACTIVATED,
    SCAN_TICKET_NOT_CONFIRMED,
    SCAN_UNKNOWN,
    SCAN_VALID,
    SCAN_WRONG_EVENT,
)
from app.models.qr_code import QrCodeModel, QrCodeTypeEnum
from app.models.scanner import ScannerModel
from app.models.ticket import TicketModel, TicketStatusEnum, TicketTypeEnum
from app.services.audit_log import ActorType, record_audit


class ScanDecision(str, Enum):
    """Outcome of a scan attempt, in the order the rules are evaluated."""

    NOT_FOUND = "NOT_FOUND"
    WRONG_EVENT = "WRONG_EVENT"
    TICKET_NOT_CONFIRMED = "TICKET_NOT_CONFIRMED"
    ALREADY_USED = "ALREADY_USED"
    NOT_ACTIVATED = "NOT_ACTIVATED"
    SUCCESS = "SUCCESS"


@dataclass(frozen=True)
class ScanResult:
    """Immutable description of a scan attempt.

    ``graduate_id`` lets the caller (and the audit trail) attribute the scan to
    the graduate even when the scan failed.
    """

    decision: ScanDecision
    message: str
    qr_code_id: int | None = None
    graduate_id: int | None = None
    code_type: QrCodeTypeEnum | None = None
    ticket_id: int | None = None


class QrServiceError(Exception):
    """Base class for domain errors raised by this service.

    These are programming/contract errors, not scan outcomes: the router layer
    catches them and maps them to an HTTP response, whereas ordinary scan
    problems are reported through :class:`ScanResult`.
    """


class TicketNotEligibleError(QrServiceError):
    """The ticket does not exist or is not CONFIRMED, so codes cannot be issued."""

    def __init__(self, ticket_id: int) -> None:
        self.ticket_id = ticket_id
        super().__init__(f"ticket {ticket_id} is not eligible for QR issuance")


class ScannerNotFoundError(QrServiceError):
    """The scanner id passed to a scan does not exist."""

    def __init__(self, scanner_id: int) -> None:
        self.scanner_id = scanner_id
        super().__init__(f"scanner {scanner_id} not found")


_COMPANION_COUNTS = {
    TicketTypeEnum.TWO_COMPANIONS: 2,
    TicketTypeEnum.THREE_COMPANIONS: 3,
}


async def _audit_scan(
    db: AsyncSession, scanner_id: int, target: str, result: ScanResult
) -> None:
    """Record one audit row for a scan attempt (FR-25 / NFR audit trail).

    Every attempt is logged — success and failure alike — so the audit trail
    shows what a scanner presented even when no code was consumed.
    """
    scanner = await db.get(ScannerModel, scanner_id)
    await record_audit(
        db,
        actor_type=ActorType.SCANNER,
        actor_id=scanner_id,
        action="qr_scanned",
        target=target,
        details=result.decision.value,
        event_id=scanner.event_id if scanner is not None else None,
        graduate_id=result.graduate_id,
        ticket_id=result.ticket_id,
    )


def _parse_code_value(code_value: str | uuid.UUID) -> uuid.UUID | None:
    """Return the QR value as a UUID, or ``None`` when it is malformed.

    A malformed value is indistinguishable from an unknown one to the scanner
    (SRS NFR privacy): both yield ``NOT_FOUND``.
    """
    try:
        return uuid.UUID(str(code_value))
    except (ValueError, AttributeError, TypeError):
        return None


async def issue_qr_codes_for_ticket(
    db: AsyncSession, ticket_id: int
) -> list[QrCodeModel]:
    """Return the QR codes a CONFIRMED ticket is entitled to.

    On the first call this creates exactly one GRADUATE code and
    ``companions_count`` COMPANION codes; on later calls it returns the
    already-issued codes unchanged (idempotent). Raises
    :class:`TicketNotEligibleError` when the ticket does not exist or is not
    CONFIRMED. The ``SELECT ... FOR UPDATE`` on the ticket serialises concurrent
    callers so a ticket is never double-issued.
    """
    ticket = (
        await db.execute(
            select(TicketModel)
            .where(TicketModel.id == ticket_id)
            .with_for_update()
        )
    ).scalar_one_or_none()

    if ticket is None or ticket.status != TicketStatusEnum.CONFIRMED:
        raise TicketNotEligibleError(ticket_id)

    existing = (
        await db.execute(
            select(QrCodeModel).where(QrCodeModel.ticket_id == ticket_id)
        )
    ).scalars().all()
    if existing:
        return list(existing)

    companion_count = _COMPANION_COUNTS.get(ticket.ticket_type, 0)
    codes = [
        QrCodeModel(
            ticket_id=ticket_id,
            code_type=QrCodeTypeEnum.GRADUATE,
            is_activated=True,
        )
    ]
    codes.extend(
        QrCodeModel(ticket_id=ticket_id, code_type=QrCodeTypeEnum.COMPANION)
        for _ in range(companion_count)
    )
    db.add_all(codes)
    await db.flush()
    return codes


async def activate_companion_codes(db: AsyncSession, ticket_id: int) -> int:
    """Activate all not-yet-active COMPANION codes of a ticket (UC-12).

    Idempotent: codes already activated are left untouched. Only flips
    ``is_activated``; never touches ``scanned_at`` / ``scanned_by_scanner_id``.
    Returns the number of codes activated.
    """
    result = await db.execute(
        update(QrCodeModel)
        .where(
            QrCodeModel.ticket_id == ticket_id,
            QrCodeModel.code_type == QrCodeTypeEnum.COMPANION,
            QrCodeModel.is_activated.is_(False),
        )
        .values(is_activated=True)
    )
    await db.flush()
    return result.rowcount


async def scan_qr_code(
    db: AsyncSession, code_value: str | uuid.UUID, scanner_id: int
) -> ScanResult:
    """Scan a QR code on behalf of a scanner (FR-25 / UC-11).

    The rules are evaluated in this fixed order so a scanner sees the single
    most relevant reason:

    1. ``NOT_FOUND``            — unknown or malformed value.
    2. ``WRONG_EVENT``          — the code belongs to another event.
    3. ``TICKET_NOT_CONFIRMED`` — the underlying ticket is not CONFIRMED.
    4. ``ALREADY_USED``         — the code already carries a ``scanned_at``.
    5. ``NOT_ACTIVATED``        — a COMPANION code whose graduate has not been
                                  scanned yet.
    6. ``SUCCESS``              — the code is consumed and (for a GRADUATE
                                  code) its COMPANION codes are activated.

    The QR row is locked with ``FOR UPDATE`` for the whole decision so two
    scanners cannot consume the same code simultaneously.
    """
    value = _parse_code_value(code_value)
    if value is None:
        result = ScanResult(ScanDecision.NOT_FOUND, SCAN_UNKNOWN)
        await _audit_scan(db, scanner_id, str(code_value), result)
        return result

    qr_record = (
        await db.execute(
            select(QrCodeModel)
            .where(QrCodeModel.code_value == value)
            .with_for_update()
        )
    ).scalar_one_or_none()
    if qr_record is None:
        result = ScanResult(ScanDecision.NOT_FOUND, SCAN_UNKNOWN)
        await _audit_scan(db, scanner_id, str(code_value), result)
        return result

    ticket = await db.get(TicketModel, qr_record.ticket_id)
    if ticket is None:
        result = ScanResult(ScanDecision.NOT_FOUND, SCAN_UNKNOWN)
        await _audit_scan(db, scanner_id, str(value), result)
        return result

    scanner = await db.get(ScannerModel, scanner_id)
    if scanner is None:
        raise ScannerNotFoundError(scanner_id)
    if scanner.event_id != ticket.event_id:
        result = ScanResult(
            ScanDecision.WRONG_EVENT,
            SCAN_WRONG_EVENT,
            qr_record.id,
            ticket.graduate_id,
            qr_record.code_type,
            ticket.id,
        )
        await _audit_scan(db, scanner_id, str(value), result)
        return result

    if ticket.status != TicketStatusEnum.CONFIRMED:
        result = ScanResult(
            ScanDecision.TICKET_NOT_CONFIRMED,
            SCAN_TICKET_NOT_CONFIRMED,
            qr_record.id,
            ticket.graduate_id,
            qr_record.code_type,
            ticket.id,
        )
        await _audit_scan(db, scanner_id, str(value), result)
        return result

    if qr_record.scanned_at is not None:
        result = ScanResult(
            ScanDecision.ALREADY_USED,
            SCAN_ALREADY_USED,
            qr_record.id,
            ticket.graduate_id,
            qr_record.code_type,
            ticket.id,
        )
        await _audit_scan(db, scanner_id, str(value), result)
        return result

    if not qr_record.is_activated:
        result = ScanResult(
            ScanDecision.NOT_ACTIVATED,
            SCAN_NOT_ACTIVATED,
            qr_record.id,
            ticket.graduate_id,
            qr_record.code_type,
            ticket.id,
        )
        await _audit_scan(db, scanner_id, str(value), result)
        return result

    qr_record.is_activated = True
    qr_record.scanned_at = datetime.now(UTC)
    qr_record.scanned_by_scanner_id = scanner_id
    if qr_record.code_type == QrCodeTypeEnum.GRADUATE:
        await activate_companion_codes(db, ticket.id)
    await db.flush()

    result = ScanResult(
        ScanDecision.SUCCESS,
        SCAN_VALID,
        qr_record.id,
        ticket.graduate_id,
        qr_record.code_type,
    )
    await _audit_scan(db, scanner_id, str(value), result)
    return result
