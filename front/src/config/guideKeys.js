export const guideKeyOf = (text) => GUIDE_KEYS[text] || null;

// How many points a guide has, and how long it takes to read (about 200 words a minute, at least one)
export function guideReading(phaseConfig) {
  const texts = [];
  for (const section of phaseConfig.sections || []) {
    texts.push(...(section.bullets || []), ...(section.steps || []));
  }
  if (phaseConfig.warning?.text) texts.push(phaseConfig.warning.text);
  const words = texts.join(' ').split(/\s+/).filter(Boolean).length;
  return { cards: texts.length, minutes: Math.max(1, Math.ceil(words / 200)) };
}
